begin;

create table if not exists public.hdx_products (
  id bigint generated by default as identity primary key,
  baserow_id bigint unique check (baserow_id > 0),
  source text not null default 'manual' check (source in ('manual', 'baserow')),
  title text not null check (length(title) between 1 and 200),
  description text not null default '' check (length(description) <= 3000),
  category text not null check (category in ('ebook', 'coloring')),
  section text not null default 'entertainment' check (section in ('education', 'entertainment')),
  language text not null default 'pl' check (language in ('pl', 'nl', 'pl/nl')),
  price numeric(12,2) not null default 0 check (price >= 0),
  published boolean not null default false,
  cover_url text,
  file_url text,
  file_name text,
  updated_at timestamptz not null default now(),
  check (source <> 'baserow' or baserow_id is not null)
);

create table if not exists public.hdx_contacts (
  id bigint generated by default as identity primary key,
  submission_id uuid not null unique,
  name text not null check (length(name) between 1 and 120),
  email text not null check (email = lower(email) and length(email) <= 254),
  company text not null default '' check (length(company) <= 200),
  message text not null check (length(message) between 1 and 5000),
  language text not null check (language in ('pl', 'nl')),
  consent boolean not null default false,
  consent_version text not null,
  submitted_at timestamptz not null default now(),
  source text not null check (source = 'website_contact'),
  status text not null default 'new' check (status in ('new', 'in_progress', 'closed')),
  confirmation_subject text not null,
  confirmation_body text not null,
  confirmation_sent boolean not null default false,
  confirmation_sent_at timestamptz
);

create table if not exists public.hdx_email_outbox (
  id uuid primary key default gen_random_uuid(),
  contact_id bigint not null unique references public.hdx_contacts(id) on delete cascade,
  recipient text not null,
  subject text not null,
  body text not null,
  status text not null default 'pending' check (status in ('pending', 'processing', 'sent', 'failed')),
  attempts integer not null default 0,
  available_at timestamptz not null default now(),
  locked_until timestamptz,
  lock_token uuid,
  created_at timestamptz not null default now(),
  sent_at timestamptz
);

alter table public.hdx_contacts add column if not exists topic text not null default 'business_offer'
  check (topic in ('business_offer', 'coloring', 'ebook', 'general'));

alter table public.hdx_products enable row level security;
alter table public.hdx_contacts enable row level security;
alter table public.hdx_email_outbox enable row level security;

-- The website uses its server key. No anonymous or logged-in visitor can
-- read personal data, paid file URLs or manipulate the queue through PostgREST.
revoke all on table public.hdx_products, public.hdx_contacts, public.hdx_email_outbox from anon, authenticated;
grant select, insert, update, delete on table public.hdx_products, public.hdx_contacts, public.hdx_email_outbox to service_role;
grant usage, select on sequence public.hdx_products_id_seq, public.hdx_contacts_id_seq to service_role;

create or replace function public.hdx_queue_confirmation()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if not new.consent then return new; end if;
  insert into public.hdx_email_outbox(contact_id, recipient, subject, body)
  values (new.id, new.email, new.confirmation_subject, new.confirmation_body);
  return new;
end;
$$;
drop trigger if exists hdx_contact_confirmation on public.hdx_contacts;
create trigger hdx_contact_confirmation after insert on public.hdx_contacts for each row execute function public.hdx_queue_confirmation();
revoke all on function public.hdx_queue_confirmation() from public, anon, authenticated;

create or replace function public.hdx_sync_baserow_products(p_products jsonb)
returns jsonb language plpgsql security invoker set search_path = '' as $$
declare synced integer;
begin
  if jsonb_typeof(p_products) <> 'array' then raise exception 'Expected catalogue array'; end if;
  insert into public.hdx_products(baserow_id, source, title, description, category, section, language, price, published, cover_url, file_url, file_name, updated_at)
  select p.baserow_id, 'baserow', p.title, p.description, p.category, p.section, p.language, p.price, p.published, p.cover_url, p.file_url, p.file_name, now()
  from jsonb_to_recordset(p_products) as p(baserow_id bigint, title text, description text, category text, section text, language text, price numeric, published boolean, cover_url text, file_url text, file_name text)
  on conflict (baserow_id) do update set source = 'baserow', title = excluded.title, description = excluded.description, category = excluded.category, section = excluded.section, language = excluded.language, price = excluded.price, published = excluded.published, cover_url = excluded.cover_url, file_url = excluded.file_url, file_name = excluded.file_name, updated_at = now();
  get diagnostics synced = row_count;
  delete from public.hdx_products where source = 'baserow'
    and baserow_id not in (select p.baserow_id from jsonb_to_recordset(p_products) as p(baserow_id bigint));
  return jsonb_build_object('synced', synced);
end;
$$;
revoke all on function public.hdx_sync_baserow_products(jsonb) from public, anon, authenticated;
grant execute on function public.hdx_sync_baserow_products(jsonb) to service_role;

create or replace function public.hdx_claim_emails(p_limit integer default 10)
returns setof public.hdx_email_outbox language plpgsql security definer set search_path = '' as $$
begin
  update public.hdx_email_outbox set status = 'failed', locked_until = null, lock_token = null
    where status = 'processing' and locked_until < now() and attempts >= 5;
  -- A lease prevents two Render instances from sending the same job at once.
  -- Recheck consent before claiming a queued confirmation.
  return query
  with jobs as (
    select q.id from public.hdx_email_outbox q
    where q.attempts < 5
      and ((q.status = 'pending' and q.available_at <= now()) or (q.status = 'processing' and q.locked_until < now()))
      and exists (select 1 from public.hdx_contacts c where c.id = q.contact_id and c.consent)
    order by q.created_at, q.id
    for update of q skip locked
    limit greatest(1, least(coalesce(p_limit, 10), 10))
  )
  update public.hdx_email_outbox q set status = 'processing', attempts = attempts + 1, locked_until = now() + interval '5 minutes', lock_token = gen_random_uuid()
  from jobs where q.id = jobs.id returning q.*;
end;
$$;
revoke all on function public.hdx_claim_emails(integer) from public, anon, authenticated;
grant execute on function public.hdx_claim_emails(integer) to service_role;

create or replace function public.hdx_finish_email(p_id uuid, p_lock_token uuid, p_sent boolean)
returns boolean language plpgsql security definer set search_path = '' as $$
declare job public.hdx_email_outbox;
begin
  update public.hdx_email_outbox set
    status = case when p_sent then 'sent' when attempts >= 5 then 'failed' else 'pending' end,
    sent_at = case when p_sent then now() else null end,
    available_at = now() + (least(3600, 60 * power(2, attempts)) * interval '1 second'),
    locked_until = null, lock_token = null
  where id = p_id and lock_token = p_lock_token and status = 'processing'
  returning * into job;
  if not found then return false; end if;
  if p_sent then
    update public.hdx_contacts set confirmation_sent = true, confirmation_sent_at = now() where id = job.contact_id;
  end if;
  return true;
end;
$$;
revoke all on function public.hdx_finish_email(uuid, uuid, boolean) from public, anon, authenticated;
grant execute on function public.hdx_finish_email(uuid, uuid, boolean) to service_role;

create index if not exists hdx_email_outbox_pending on public.hdx_email_outbox(available_at) where status in ('pending', 'processing');

-- New buckets do not change existing buckets. Public buckets are only for
-- covers and genuinely free publications; paid files belong in a private bucket.
insert into storage.buckets(id, name, public, file_size_limit, allowed_mime_types)
values ('hdx-covers', 'hdx-covers', true, 10485760, array['image/jpeg', 'image/png', 'image/webp']),
       ('hdx-free-ebooks', 'hdx-free-ebooks', true, 52428800, array['application/pdf']),
       ('hdx-private-files', 'hdx-private-files', false, 52428800, array['application/pdf'])
on conflict (id) do nothing;

commit;
